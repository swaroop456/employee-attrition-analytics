numeric_cols = df_corr.select_dtypes(include=[np.number]).columns
corr_matrix = df_corr[numeric_cols].corr()

top_corr = corr_matrix["attrition_binary"].drop("attrition_binary").abs().sort_values(ascending=False)
print("Top 3 features correlated with attrition:\n", top_corr.head(3))

