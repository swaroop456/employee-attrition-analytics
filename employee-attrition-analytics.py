print("Attrition rate by overtime:\n", overtime_attrition)

cat_cols = df.select_dtypes(include="object").columns.tolist()
cat_cols = [c for c in cat_cols if c not in ["attrition", "join_date"]]
print("Categorical columns:", cat_cols)

ohe_check = OneHotEncoder(drop="first")
ohe_check.fit(df[cat_cols])
print("Number of OneHotEncoder output columns (drop='first'):", ohe_check.get_feature_names_out().size)

target_col = "attrition"
drop_cols = ["employee_id", "join_date", target_col]

X = df.drop(columns=drop_cols)
y = df[target_col].map({"Yes": 1, "No": 0})

num_cols = X.select_dtypes(include=[np.number]).columns.tolist()
cat_cols = X.select_dtypes(include="object").columns.tolist()
print("Numeric columns:", num_cols)
print("Categorical columns:", cat_cols)

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42
)

print("\nTrain attrition rate:", y_train.mean())
print("Test attrition rate:", y_test.mean())
# stratify=y keeps the Yes/No ratio identical in train and test.
# Without it, a random split could over- or under-represent the minority
# "Yes" class in either set, which would skew evaluation metrics.

preprocessor = ColumnTransformer(transformers=[
    ("num", StandardScaler(), num_cols),
    ("cat", OneHotEncoder(drop="first"), cat_cols)
])

X_train_transformed = preprocessor.fit_transform(X_train)
X_test_transformed = preprocessor.transform(X_test)  # fit only on train, transform both

print("\nX_train shape after preprocessing:", X_train_transformed.shape)

feature_names = preprocessor.get_feature_names_out()

log_reg = LogisticRegression(max_iter=1000, class_weight="balanced")
log_reg.fit(X_train_transformed, y_train)

y_pred_lr = log_reg.predict(X_test_transformed)
y_proba_lr = log_reg.predict_proba(X_test_transformed)[:, 1]

print("Logistic Regression Results")
print("Precision:", precision_score(y_test, y_pred_lr))
print("Recall:", recall_score(y_test, y_pred_lr))
print("F1-score:", f1_score(y_test, y_pred_lr))
print("ROC-AUC:", roc_auc_score(y_test, y_proba_lr))
print("\n", classification_report(y_test, y_pred_lr))

cm = confusion_matrix(y_test, y_pred_lr)
plt.figure(figsize=(6, 5))
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
            xticklabels=["No", "Yes"], yticklabels=["No", "Yes"])
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix - Logistic Regression")
plt.savefig("output/confusion_matrix_lr.png")
plt.show()

# False positive: predicted "will leave" but employee actually stayed
#   -> wasted retention effort/budget on someone who wasn't at risk.
# False negative: predicted "will stay" but employee actually left
#   -> missed a real flight risk, no intervention happened, company loses the employee.

dt = DecisionTreeClassifier(class_weight="balanced", random_state=42)
dt.fit(X_train_transformed, y_train)
y_pred_dt = dt.predict(X_test_transformed)
y_proba_dt = dt.predict_proba(X_test_transformed)[:, 1]

rf = RandomForestClassifier(class_weight="balanced", random_state=42)
rf.fit(X_train_transformed, y_train)
y_pred_rf = rf.predict(X_test_transformed)
y_proba_rf = rf.predict_proba(X_test_transformed)[:, 1]

for name, y_pred, y_proba in [("Decision Tree", y_pred_dt, y_proba_dt), ("Random Forest", y_pred_rf, y_proba_rf)]:
    print(f"\n{name} Results")
    print("Precision:", precision_score(y_test, y_pred))
    print("Recall:", recall_score(y_test, y_pred))
    print("F1-score:", f1_score(y_test, y_pred))
    print("ROC-AUC:", roc_auc_score(y_test, y_proba))

plt.figure(figsize=(8, 6))
for name, y_proba in [("Logistic Regression", y_proba_lr), ("Decision Tree", y_proba_dt), ("Random Forest", y_proba_rf)]:
    fpr, tpr, _ = roc_curve(y_test, y_proba)
    plt.plot(fpr, tpr, label=f"{name} (AUC={roc_auc_score(y_test, y_proba):.3f})")

