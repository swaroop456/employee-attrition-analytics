X_numeric_scaled = StandardScaler().fit_transform(df[num_cols])

inertia_list = []
k_range = range(2, 11)
for k in k_range:
    km = KMeans(n_clusters=k, random_state=42, n_init=10)
    km.fit(X_numeric_scaled)
    inertia_list.append(km.inertia_)

plt.figure(figsize=(8, 5))
plt.plot(list(k_range), inertia_list, marker="o")
plt.xlabel("Number of Clusters (k)")
plt.ylabel("Inertia")
plt.title("Elbow Curve")
plt.savefig("output/elbow_curve.png")
plt.show()

silhouette_scores = []
for k in k_range:
    km = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = km.fit_predict(X_numeric_scaled)
    silhouette_scores.append(silhouette_score(X_numeric_scaled, labels))

plt.figure(figsize=(8, 5))
plt.plot(list(k_range), silhouette_scores, marker="o", color="orange")
plt.xlabel("Number of Clusters (k)")
plt.ylabel("Silhouette Score")
plt.title("Silhouette Score vs k")
plt.savefig("output/silhouette_scores.png")
plt.show()

best_k_silhouette = list(k_range)[np.argmax(silhouette_scores)]
print("Best k by silhouette score:", best_k_silhouette)

chosen_k = best_k_silhouette  # or override manually based on the elbow plot, e.g. chosen_k = 4

kmeans_final = KMeans(n_clusters=chosen_k, random_state=42, n_init=10)
df["cluster"] = kmeans_final.fit_predict(X_numeric_scaled)

cluster_attrition = df.groupby("cluster")["attrition"].apply(lambda x: (x == "Yes").mean()).sort_values(ascending=False)
print("Attrition rate by cluster:\n", cluster_attrition)
print("\nHighest-attrition cluster:", cluster_attrition.idxmax())

plt.figure(figsize=(8, 5))
cluster_attrition.plot(kind="bar", color="teal")
plt.title(f"Attrition Rate by Cluster (k={chosen_k})")
plt.ylabel("Attrition Rate")
plt.savefig("output/cluster_attrition.png")
plt.show()

reg_drop_cols = ["employee_id", "join_date", "attrition", "monthly_income_usd"]
X_reg = df.drop(columns=reg_drop_cols + (["cluster"] if "cluster" in df.columns else []))
y_reg = df["monthly_income_usd"]

reg_num_cols = X_reg.select_dtypes(include=[np.number]).columns.tolist()
reg_cat_cols = X_reg.select_dtypes(include="object").columns.tolist()

X_train_reg, X_test_reg, y_train_reg, y_test_reg = train_test_split(
    X_reg, y_reg, test_size=0.2, random_state=42
)

reg_preprocessor = ColumnTransformer(transformers=[
    ("num", StandardScaler(), reg_num_cols),
    ("cat", OneHotEncoder(drop="first"), reg_cat_cols)
])

X_train_reg_t = reg_preprocessor.fit_transform(X_train_reg)
X_test_reg_t = reg_preprocessor.transform(X_test_reg)
reg_feature_names = reg_preprocessor.get_feature_names_out()

lin_reg = LinearRegression()
lin_reg.fit(X_train_reg_t, y_train_reg)
y_pred_lin = lin_reg.predict(X_test_reg_t)

rf_reg = RandomForestRegressor(random_state=42)
rf_reg.fit(X_train_reg_t, y_train_reg)
y_pred_rf_reg = rf_reg.predict(X_test_reg_t)

for name, y_pred in [("Linear Regression", y_pred_lin), ("Random Forest Regressor", y_pred_rf_reg)]:
    r2 = r2_score(y_test_reg, y_pred)
    rmse = np.sqrt(mean_squared_error(y_test_reg, y_pred))
    print(f"{name} -> R2: {r2:.4f}, RMSE: {rmse:.2f}")

coef_series = pd.Series(lin_reg.coef_, index=reg_feature_names).sort_values(key=abs, ascending=False)
print("Top 5 features by coefficient magnitude:\n", coef_series.head(5))

top_feature = coef_series.index[0]
top_coef = coef_series.iloc[0]
print(f"\n'{top_feature}' has the strongest association with income.")
print(f"Interpretation: holding other features constant, a one-unit increase in this "
      f"(standardized) feature is associated with a ${top_coef:,.2f} change in monthly income.")

