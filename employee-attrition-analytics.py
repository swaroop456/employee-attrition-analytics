axes[0].set_ylabel("Monthly Income (USD)")

overtime_attrition = df.groupby("overtime")["attrition"].apply(lambda x: (x == "Yes").mean())
overtime_attrition.plot(kind="bar", ax=axes[1], color="#C44E52")
axes[1].set_title("Attrition Rate by Overtime")
